/**
 * P25: many assistant labels were written only in Arabic, so English and French users saw Arabic.
 * [L] translates those labels. Arabic stays exactly as written; a label without a translation also
 * stays as written (never blank, never crashes).
 */
internal object AssistantLang {
    var language by mutableStateOf(AppLanguage.ARABIC)
}

internal class L10nRule(val regex: Regex, val en: String, val fr: String) {
    fun render(match: MatchResult, french: Boolean): String {
        var out = if (french) fr else en
        for (i in 1 until match.groupValues.size) out = out.replace("{" + i + "}", match.groupValues[i])
        return out
    }
}

internal fun L(ar: String): String {
    val language = AssistantLang.language
    if (language == AppLanguage.ARABIC) return ar
    val french = language == AppLanguage.FRENCH
    L10N_TABLE[ar]?.let { return if (french) it.second else it.first }
    for (rule in L10N_RULES) {
        val match = rule.regex.matchEntire(ar) ?: continue
        return rule.render(match, french).replace("ج.م", "EGP")
    }
    return ar.replace("ج.م", "EGP")
}

